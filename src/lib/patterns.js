// SQL Injection detection patterns with severity and descriptions
export const SQL_PATTERNS = [
  {
    id: 'tautology',
    name: 'Tautology Attack',
    regex: /'\s*(OR|or)\s*'?\s*['"']?\s*=\s*|OR\s+1\s*=\s*1|OR\s+['"]\s*=\s*['"]/gi,
    severity: 9,
    description: 'Always-true condition to bypass authentication',
    example: "' OR 1=1 --",
  },
  {
    id: 'union_select',
    name: 'UNION SELECT',
    regex: /UNION\s+(ALL\s+)?SELECT/gi,
    severity: 10,
    description: 'Attempts to extract data from other database tables',
    example: "' UNION SELECT username, password FROM users --",
  },
  {
    id: 'comment_sequence',
    name: 'SQL Comment Injection',
    regex: /(--\s|#\s|#$|\/\*|\*\/|--$)/g,
    severity: 6,
    description: 'Uses SQL comments to truncate the original query',
    example: "admin' --",
  },
  {
    id: 'stacked_query',
    name: 'Stacked Query',
    regex: /;\s*(DROP|DELETE|INSERT|UPDATE|ALTER|CREATE|EXEC|TRUNCATE)/gi,
    severity: 10,
    description: 'Injects additional destructive SQL statements',
    example: "'; DROP TABLE users; --",
  },
  {
    id: 'time_based',
    name: 'Time-based Blind SQLi',
    regex: /(SLEEP\s*\(|BENCHMARK\s*\(|WAITFOR\s+DELAY|pg_sleep)/gi,
    severity: 8,
    description: 'Uses time delays to extract data from blind SQL injection',
    example: "' OR SLEEP(5) --",
  },
  {
    id: 'error_based',
    name: 'Error-based SQLi',
    regex: /(EXTRACTVALUE|UPDATEXML|XMLTYPE|UTL_INADDR|CONVERT\s*\()/gi,
    severity: 8,
    description: 'Exploits database error messages to extract data',
    example: "' AND EXTRACTVALUE(1, CONCAT(0x7e, (SELECT version()))) --",
  },
  {
    id: 'data_exfil',
    name: 'Data Exfiltration',
    regex: /(LOAD_FILE\s*\(|INTO\s+(OUT|DUMP)FILE|INTO\s+DUMPFILE)/gi,
    severity: 10,
    description: 'Attempts to read/write files on the server',
    example: "' UNION SELECT LOAD_FILE('/etc/passwd') --",
  },
  {
    id: 'char_obfuscation',
    name: 'Character Obfuscation',
    regex: /(CHAR\s*\(|CHR\s*\(|0x[0-9a-fA-F]{4,}|CONCAT\s*\()/gi,
    severity: 7,
    description: 'Uses character encoding to evade simple filters',
    example: "' OR CHAR(49)=CHAR(49) --",
  },
  {
    id: 'subquery',
    name: 'Subquery Injection',
    regex: /\(\s*SELECT\s/gi,
    severity: 8,
    description: 'Embeds subqueries to extract or manipulate data',
    example: "' OR (SELECT COUNT(*) FROM users) > 0 --",
  },
  {
    id: 'string_termination',
    name: 'String Termination',
    regex: /('\s*;|'\s*\)|"\s*;|"\s*\))/g,
    severity: 5,
    description: 'Attempts to break out of string context in SQL',
    example: "admin');",
  },
  {
    id: 'boolean_blind',
    name: 'Boolean-based Blind SQLi',
    regex: /(AND\s+\d+\s*=\s*\d+|AND\s+SUBSTRING|AND\s+ASCII|AND\s+LENGTH)/gi,
    severity: 7,
    description: 'Uses boolean conditions to extract data one bit at a time',
    example: "' AND SUBSTRING(username,1,1)='a' --",
  },
  {
    id: 'single_quote',
    name: 'Single Quote (possible probe)',
    regex: /^'$|'\s*$|^\s*'/,
    severity: 3,
    description: 'Lone single quote — common first step in probing for SQLi',
    example: "'",
  },
];

